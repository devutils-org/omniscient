//! The two network rows of a request: `net_rx` and `net_tx`.
//!
//! A child of `request.rs`, declared there with a `#[path]` so that the programs
//! that follow a request and the ones that follow its socket share one stack
//! layout, one storage value and one record without a registration line in
//! `src/bpf/mod.rs`.
//!
//! ## What the rows are
//!
//! **`net_rx`** is the time from the request's first byte reaching the server's
//! socket to the serving thread taking it: the bytes sat in the socket, or the
//! thread sat in `recv` waiting for the rest of them. Two stretches, one on each
//! side of the birth:
//!
//! - *before* it, from the first byte's arrival to the `request__start` probe --
//!   which is where a client that sends half its request and pauses puts its
//!   pause, because the server cannot declare a request it has not parsed;
//! - *inside* the life, every interruptible sleep of the serving thread in
//!   `sk_wait_data` on that same socket -- a server that declares the request at
//!   its headers and then reads a body.
//!
//! **`net_tx`** is the time from the response leaving the thread to it leaving
//! the stack, and it is two stretches too:
//!
//! - *inside* the life, every sleep in `sk_stream_wait_memory` on the socket:
//!   the send blocked because the send buffer was full, which on a connection
//!   whose peer reads slowly means the peer's window was closed;
//! - *after* the end, from `request__done` to the moment the last byte the
//!   server had queued by then was transmitted -- `snd_nxt` reaching the
//!   `write_seq` the end saw. A send returns once the bytes are *queued*; the
//!   request is not out of the stack until they are sent.
//!
//! The waits inside the life were counted as `sleep_ns` before this file, which
//! the vertical session printed as `lock_wait`. They are routed now, at the
//! point where `settle` decides what a sleep was, and `sleep_ns` is what is left.
//!
//! ## Why the rows are KEY and not IDENTITY
//!
//! Everything else in the request's table is read off the serving thread, which
//! carries the request's id in its own storage. Nothing on the receive or the
//! transmit path runs in that thread: the first byte is queued in softirq, in
//! whatever the cpu was running -- on loopback, the *client's* send -- and the
//! last byte leaves when the peer's acknowledgement opens the window, in the
//! peer's context. What ties those moments to the request is the socket's
//! cookie, matched between the program that saw the byte and the probe that
//! named the socket. That is a key the two sides agree on, not an identity one
//! of them propagated, and the ladder says `KEY`.
//!
//! ## Where the socket comes from: the server says so
//!
//! Both probes take a second argument, the descriptor the request was received
//! on and answered on: `request__start(id, fd)`, `request__done(id, fd)`. The
//! programs walk `current->files` to the `struct sock` behind it and read its
//! cookie. The alternative the ninth wave left open -- the thread's last receive
//! -- was rejected for the reason the birth itself is declared: a thread that
//! received from a backend after its client (a proxy, a cache fill) would have
//! its request's network rows read off the wrong connection, and nothing in the
//! numbers would say so. A probe with one argument still works; its request has
//! no network rows, and the run says why.
//!
//! ## The cookie is generated by the arrival, and read by the probes
//!
//! A uprobe program cannot call `bpf_get_socket_cookie`: the helper wants a BTF
//! pointer to the socket, and the tracing programs are the only ones handed
//! one. So the arrival program -- an fentry on `tcp_data_ready`, typed -- asks
//! for the cookie, which *assigns* it on first use, and the probes read it back
//! out of `sk->__sk_common.skc_cookie`. A socket whose first byte was not seen
//! has no cookie there, and its request says so rather than inventing one.
//!
//! ## The race at the end, and why there is a compare-and-exchange
//!
//! The end runs in the serving thread; the last transmission runs wherever the
//! peer's acknowledgement is processed, on another cpu, possibly at the same
//! instant. The end *arms* the socket's entry with the sequence number to wait
//! for and then reads `snd_nxt`; the transmit program writes `snd_nxt` (the
//! kernel does, just before it runs) and then reads the arming. Each side's
//! write is an atomic read-modify-write before its read, so at least one of them
//! sees the other, and whichever reaches the target first claims the entry with
//! a compare-and-exchange. Exactly one of them stamps the drain: the end, when
//! everything had already left, or the transmit program, which publishes a
//! drain record the collector joins to the request by its id.

use super::*;
use crate::bpf::attach::fentry::{self, Link, Side, GET_SOCKET_COOKIE};
use crate::bpf::insn::{read_field, read_narrow, read_pointer};

/// `S_NETWAIT` values: which of the socket's waits the thread is in.
pub(super) const WAIT_RX: i32 = 1;
pub(super) const WAIT_TX: i32 = 2;

// ------------------------------------------------------------- net flags
//
// On the record, beside the request: what the programs could and could not
// follow of its socket.

/// The probes named a socket.
pub(super) const NET_DECLARED: u32 = 1;
/// The descriptor did not lead to a socket.
pub(super) const NET_NO_SOCKET: u32 = 2;
/// The socket's first byte was not seen: it arrived before the programs were
/// attached, it arrived with the previous request's, or the socket's entry was
/// evicted in between.
pub(super) const NET_RX_UNSEEN: u32 = 4;
/// Bytes were still queued at the end: a drain record follows.
pub(super) const NET_TX_PENDING: u32 = 8;
/// The end named a different socket from the birth.
pub(super) const NET_OTHER_SOCKET: u32 = 16;
/// The socket's entry was gone at the end, so the drain was not followed.
pub(super) const NET_TX_UNSEEN: u32 = 32;

/// Set on a record published by the transmit program rather than by a probe:
/// the last byte of a request's response left the stack.
pub const DRAINED: u32 = 4;

// ------------------------------------------------------------- the socket map

/// One entry per TCP socket that received data while the programs ran, keyed
/// by cookie. LRU, because the arrival program sees every socket on the
/// machine and cannot tell the server's from anyone else's before the probe
/// names it.
const BPF_MAP_TYPE_LRU_HASH: u32 = 9;
const MAX_SOCKETS: u32 = 16384;

/// The arrival of the oldest byte no request has claimed yet.
const K_RX_SINCE: i16 = 0;
/// The request live on the socket, whose later arrivals are its own.
const K_LIVE: i16 = 8;
/// The request whose response is draining: when it ended, its id, its thread.
const K_DONE: i16 = 16;
const K_ID: i16 = 24;
const K_TARGET: i16 = 32;
const K_TID: i16 = 36;
/// One while a drain is waited for; claimed by compare-and-exchange.
const K_ARMED: i16 = 40;
pub(super) const SOCKET_BYTES: usize = 48;

/// `BPF_NOEXIST`: an arrival inserts an entry only where there is none.
const BPF_NOEXIST: i32 = 1;

// ------------------------------------------------------------- instructions

const BPF_STX_ATOMIC_DW: u8 = 0x03 | 0x18 | 0xc0;
const BPF_FETCH: i32 = 0x01;
const BPF_ADD: i32 = 0x00;
const BPF_XCHG: i32 = 0xe0 | BPF_FETCH;
const BPF_CMPXCHG: i32 = 0xf0 | BPF_FETCH;

fn insn(code: u8, dst: u8, src: u8, off: i16, imm: i32) -> Insn {
    Insn {
        code,
        regs: (dst & 0xf) | ((src & 0xf) << 4),
        off,
        imm,
    }
}

/// `src = atomic_fetch_add((u64 *)(dst + off), src)`: an atomic read when
/// `src` is zero, and a full barrier on every architecture the kernel JITs.
fn fetch_add(dst: u8, off: i16, src: u8) -> Insn {
    insn(BPF_STX_ATOMIC_DW, dst, src, off, BPF_ADD | BPF_FETCH)
}

/// `src = xchg((u64 *)(dst + off), src)`
fn xchg(dst: u8, off: i16, src: u8) -> Insn {
    insn(BPF_STX_ATOMIC_DW, dst, src, off, BPF_XCHG)
}

/// `r0 = cmpxchg((u64 *)(dst + off), r0, src)`
fn cmpxchg(dst: u8, off: i16, src: u8) -> Insn {
    insn(BPF_STX_ATOMIC_DW, dst, src, off, BPF_CMPXCHG)
}

/// `field |= flag`, a four-byte field at `off` from `base`.
fn set_flag(program: &mut Program, base: u8, off: i16, flag: u32) {
    program.push(Insn::ldx(BPF_W, 1, base, off));
    program.push(Insn::or64_imm(1, flag as i32));
    program.push(Insn::stx(BPF_W, base, off, 1));
}

// ------------------------------------------------------------- offsets

/// Every field the walk from a descriptor to a socket's sequence numbers reads,
/// out of the running kernel's BTF.
#[derive(Debug, Clone, Copy)]
pub(super) struct Offsets {
    files: i32,
    fdt: i32,
    max_fds: i32,
    fd: i32,
    private_data: i32,
    socket_file: i32,
    socket_sk: i32,
    cookie: i32,
    write_seq: i32,
    snd_nxt: i32,
}

impl Offsets {
    pub(super) fn read(btf: &Btf) -> Result<Self, String> {
        let at = |structure: &str, member: &str| btf.member_offset(structure, member);
        Ok(Self {
            files: at("task_struct", "files")?,
            fdt: at("files_struct", "fdt")?,
            max_fds: at("fdtable", "max_fds")?,
            fd: at("fdtable", "fd")?,
            private_data: at("file", "private_data")?,
            socket_file: at("socket", "file")?,
            socket_sk: at("socket", "sk")?,
            cookie: at("sock", "__sk_common")? + at("sock_common", "skc_cookie")?,
            write_seq: at("tcp_sock", "write_seq")?,
            snd_nxt: at("tcp_sock", "snd_nxt")?,
        })
    }
}

// ------------------------------------------------------------- the walk

/// Leaves the `struct sock *` behind the descriptor at `ARG1` in `r8`, or
/// jumps to `fail`.
///
/// `current->files->fdt->fd[fd]->private_data->sk`, each step a
/// `bpf_probe_read_kernel`, with the two checks that keep a wrong descriptor
/// from reading as a socket: the descriptor is below the table's `max_fds`,
/// and the `struct socket` it leads to points back at the same `struct file`
/// -- which a file that is not a socket, whose `private_data` is something
/// else, does not. Clobbers `r0`-`r5` and `r9`; `r6` and `r7` survive.
fn socket_of_descriptor(program: &mut Program, at: &Offsets, fail: &'static str) {
    program.push(Insn::call(GET_CURRENT_TASK_BTF));
    program.push(Insn::mov64_reg(9, 0));
    read_pointer(program, SCRATCH, 9, 9, at.files);
    program.jump_to(fail, Insn::jeq_imm(9, 0, 0));
    read_pointer(program, SCRATCH, 9, 9, at.fdt);
    program.jump_to(fail, Insn::jeq_imm(9, 0, 0));
    read_narrow(program, LIMIT, 4, 9, at.max_fds);
    program.push(Insn::ldx(BPF_W, 1, R10, LIMIT));
    program.push(Insn::ldx(BPF_DW, 2, R10, ARG1));
    // Unsigned: a negative descriptor, zero-extended, is above every limit.
    program.jump_to(fail, Insn::jge_reg(2, 1, 0));
    read_pointer(program, SCRATCH, 9, 9, at.fd);
    program.jump_to(fail, Insn::jeq_imm(9, 0, 0));
    program.push(Insn::ldx(BPF_DW, 2, R10, ARG1));
    program.push(Insn::lsh64_imm(2, 3));
    program.push(Insn::add64_reg(9, 2));
    read_pointer(program, SCRATCH, 9, 9, 0);
    program.jump_to(fail, Insn::jeq_imm(9, 0, 0));
    program.push(Insn::stx(BPF_DW, R10, FILE_PTR, 9));
    read_pointer(program, SCRATCH, 8, 9, at.private_data);
    program.jump_to(fail, Insn::jeq_imm(8, 0, 0));
    read_pointer(program, SCRATCH, 1, 8, at.socket_file);
    program.push(Insn::ldx(BPF_DW, 2, R10, FILE_PTR));
    program.jump_to(fail, Insn::jne_reg(1, 2, 0));
    read_pointer(program, SCRATCH, 8, 8, at.socket_sk);
    program.jump_to(fail, Insn::jeq_imm(8, 0, 0));
}

/// The cookie of the socket in `r8` into `SOCK_KEY`: zero when nothing has
/// asked for one yet, which here means its first byte was never seen.
fn cookie_of(program: &mut Program, at: &Offsets) {
    program.push(Insn::st_imm(BPF_DW, R10, SOCK_KEY, 0));
    read_field(program, SOCK_KEY, 8, 8, at.cookie);
}

fn lookup_socket(program: &mut Program, sockets: i32) {
    program.extend(Insn::load_map_fd(1, sockets));
    program.push(Insn::mov64_reg(2, R10));
    program.push(Insn::add64_imm(2, SOCK_KEY as i32));
    program.push(Insn::call(helper::MAP_LOOKUP_ELEM));
}

// ------------------------------------------------------------- in the probes

/// The birth's half: the socket the request arrived on, and when its first
/// byte did.
///
/// Runs after the birth has written the id and the birth time into the value
/// in `r7`. Claims the socket's oldest unclaimed arrival -- the request's first
/// byte -- and marks the socket live, so that bytes arriving while the request
/// is served are not taken for the next request's first.
pub(super) fn birth_socket(program: &mut Program, at: &Offsets, sockets: i32) {
    program.push(Insn::st_imm(BPF_W, 7, S_NET_FLAGS, NET_DECLARED as i32));
    socket_of_descriptor(program, at, "rx_no_socket");
    cookie_of(program, at);
    program.push(Insn::ldx(BPF_DW, 1, R10, SOCK_KEY));
    program.jump_to("rx_unseen", Insn::jeq_imm(1, 0, 0));
    program.push(Insn::stx(BPF_DW, 7, S_COOKIE, 1));
    lookup_socket(program, sockets);
    program.jump_to("rx_unseen", Insn::jeq_imm(0, 0, 0));
    program.push(Insn::mov64_reg(9, 0));
    program.push(Insn::ldx(BPF_DW, 1, R10, ARG0));
    program.push(Insn::stx(BPF_DW, 9, K_LIVE, 1));
    program.push(Insn::ldx(BPF_DW, 2, 9, K_RX_SINCE));
    program.push(Insn::st_imm(BPF_DW, 9, K_RX_SINCE, 0));
    program.jump_to("rx_unseen", Insn::jeq_imm(2, 0, 0));
    // A stamp after the birth is an arrival that raced it on another cpu: not
    // this request's first byte, whose arrival the birth itself follows.
    program.push(Insn::ldx(BPF_DW, 3, R10, NOW));
    program.jump_to("rx_unseen", Insn::jgt_reg(2, 3, 0));
    program.push(Insn::stx(BPF_DW, 7, S_FIRST_BYTE, 2));
    program.jump_to("rx_done", Insn::ja());

    program.label("rx_no_socket");
    set_flag(program, 7, S_NET_FLAGS, NET_NO_SOCKET);
    program.jump_to("rx_done", Insn::ja());
    program.label("rx_unseen");
    set_flag(program, 7, S_NET_FLAGS, NET_RX_UNSEEN);
    program.label("rx_done");
}

/// The end's half: arm the socket's entry with the last byte to wait for, or
/// stamp the drain here when it has already left.
///
/// Runs after the record has been filled from the value in `r7`, and writes
/// only the record's `R_DRAINED` and `R_NET_FLAGS`.
pub(super) fn end_socket(program: &mut Program, at: &Offsets, sockets: i32) {
    program.push(Insn::ldx(BPF_DW, 1, 7, S_COOKIE));
    program.jump_to("tx_done", Insn::jeq_imm(1, 0, 0));
    socket_of_descriptor(program, at, "tx_no_socket");
    cookie_of(program, at);
    program.push(Insn::ldx(BPF_DW, 1, R10, SOCK_KEY));
    program.push(Insn::ldx(BPF_DW, 2, 7, S_COOKIE));
    program.jump_to("tx_other", Insn::jne_reg(1, 2, 0));
    // What the server had queued by its end: the response.
    read_narrow(program, SEQ, 4, 8, at.write_seq);
    lookup_socket(program, sockets);
    program.jump_to("tx_unseen", Insn::jeq_imm(0, 0, 0));
    program.push(Insn::mov64_reg(9, 0));
    // Whatever arrived while the request was live was its own, and the next
    // request's first byte is the first to arrive after this.
    program.push(Insn::st_imm(BPF_DW, 9, K_RX_SINCE, 0));
    program.push(Insn::st_imm(BPF_DW, 9, K_LIVE, 0));
    program.push(Insn::ldx(BPF_W, 1, R10, SEQ));
    program.push(Insn::stx(BPF_W, 9, K_TARGET, 1));
    program.push(Insn::ldx(BPF_DW, 1, R10, NOW));
    program.push(Insn::stx(BPF_DW, 9, K_DONE, 1));
    program.push(Insn::ldx(BPF_DW, 1, 7, S_ID));
    program.push(Insn::stx(BPF_DW, 9, K_ID, 1));
    program.push(Insn::ldx(BPF_W, 1, R10, TID));
    program.push(Insn::stx(BPF_W, 9, K_TID, 1));
    // Armed with a read-modify-write, a barrier: the fields above are visible
    // to the transmit program before the arming is, and the read of `snd_nxt`
    // below cannot be hoisted above it.
    program.push(Insn::mov64_imm(1, 1));
    program.push(xchg(9, K_ARMED, 1));
    read_narrow(program, LIMIT, 4, 8, at.snd_nxt);
    reached(program, LIMIT, SEQ, "tx_reached", "tx_pending");
    program.label("tx_reached");
    program.push(Insn::mov64_imm(0, 1));
    program.push(Insn::mov64_imm(1, 0));
    program.push(cmpxchg(9, K_ARMED, 1));
    // Lost: the transmit program reached the target first and publishes it.
    program.jump_to("tx_pending", Insn::jne_imm(0, 1, 0));
    program.push(Insn::ldx(BPF_DW, 1, R10, NOW));
    program.push(Insn::stx(BPF_DW, R10, REC + R_DRAINED, 1));
    program.jump_to("tx_done", Insn::ja());

    program.label("tx_pending");
    set_flag(program, R10, REC + R_NET_FLAGS, NET_TX_PENDING);
    program.jump_to("tx_done", Insn::ja());
    program.label("tx_no_socket");
    set_flag(program, R10, REC + R_NET_FLAGS, NET_NO_SOCKET);
    program.jump_to("tx_done", Insn::ja());
    program.label("tx_other");
    set_flag(program, R10, REC + R_NET_FLAGS, NET_OTHER_SOCKET);
    program.jump_to("tx_done", Insn::ja());
    program.label("tx_unseen");
    set_flag(program, R10, REC + R_NET_FLAGS, NET_TX_UNSEEN);
    program.label("tx_done");
}

/// Jumps to `yes` when the four-byte sequence number at `sent` has reached the
/// one at `target`, modulo 2^32, and to `no` otherwise.
///
/// TCP's `after()`: the difference, as a signed 32-bit number, is not
/// negative. Shifted into the top half so that a signed 64-bit comparison
/// reads the 32-bit sign.
fn reached(program: &mut Program, sent: i16, target: i16, yes: &'static str, no: &'static str) {
    program.push(Insn::ldx(BPF_W, 1, R10, sent));
    program.push(Insn::ldx(BPF_W, 2, R10, target));
    program.push(Insn::sub64_reg(1, 2));
    program.push(Insn::lsh64_imm(1, 32));
    program.jump_to(yes, Insn::jsge_imm(1, 0, 0));
    program.jump_to(no, Insn::ja());
}

// ------------------------------------------------------------- the tracing programs

/// The file descriptors the socket programs are built against.
#[derive(Debug, Clone, Copy)]
pub(super) struct NetMaps {
    pub storage: i32,
    pub sockets: i32,
    pub ring: i32,
    pub counters: i32,
}

/// `tcp_data_ready(sk)`: data was queued on a socket. The first byte no
/// request has claimed is stamped; everything after it until a birth claims
/// it, and everything that arrives while a request is live, is not.
fn arrival_instructions(maps: NetMaps) -> Result<Vec<Insn>, String> {
    let mut program = Program::new();
    program.push(Insn::ldx(BPF_DW, 1, 1, 0));
    program.jump_to("done", Insn::jeq_imm(1, 0, 0));
    program.push(Insn::call(GET_SOCKET_COOKIE));
    program.push(Insn::stx(BPF_DW, R10, SOCK_KEY, 0));
    program.jump_to("done", Insn::jeq_imm(0, 0, 0));
    lookup_socket(&mut program, maps.sockets);
    program.jump_to("insert", Insn::jeq_imm(0, 0, 0));
    program.push(Insn::mov64_reg(7, 0));
    program.push(Insn::ldx(BPF_DW, 1, 7, K_LIVE));
    program.jump_to("done", Insn::jne_imm(1, 0, 0));
    program.push(Insn::ldx(BPF_DW, 1, 7, K_RX_SINCE));
    program.jump_to("done", Insn::jne_imm(1, 0, 0));
    // Two cpus can queue onto one socket at once; the first stamp stands.
    program.push(Insn::call(helper::KTIME_GET_NS));
    program.push(Insn::mov64_reg(1, 0));
    program.push(Insn::mov64_imm(0, 0));
    program.push(cmpxchg(7, K_RX_SINCE, 1));
    program.jump_to("done", Insn::ja());

    program.label("insert");
    for slot in 0..(SOCKET_BYTES / 8) as i16 {
        program.push(Insn::st_imm(BPF_DW, R10, SOCK_VALUE + slot * 8, 0));
    }
    program.push(Insn::call(helper::KTIME_GET_NS));
    program.push(Insn::stx(BPF_DW, R10, SOCK_VALUE + K_RX_SINCE, 0));
    program.extend(Insn::load_map_fd(1, maps.sockets));
    program.push(Insn::mov64_reg(2, R10));
    program.push(Insn::add64_imm(2, SOCK_KEY as i32));
    program.push(Insn::mov64_reg(3, R10));
    program.push(Insn::add64_imm(3, SOCK_VALUE as i32));
    program.push(Insn::mov64_imm(4, BPF_NOEXIST));
    program.push(Insn::call(helper::MAP_UPDATE_ELEM));
    finish(program)
}

/// `tcp_event_new_data_sent(sk, skb)`, at its exit: `snd_nxt` has moved. When
/// it reaches the target an ended request armed the socket with, the
/// response has left the stack, and whichever of this and the end claims the
/// arming first says when.
fn transmit_instructions(at: &Offsets, maps: NetMaps) -> Result<Vec<Insn>, String> {
    let mut program = Program::new();
    program.push(Insn::ldx(BPF_DW, 6, 1, 0));
    program.jump_to("done", Insn::jeq_imm(6, 0, 0));
    program.push(Insn::mov64_reg(1, 6));
    program.push(Insn::call(GET_SOCKET_COOKIE));
    program.push(Insn::stx(BPF_DW, R10, SOCK_KEY, 0));
    lookup_socket(&mut program, maps.sockets);
    program.jump_to("done", Insn::jeq_imm(0, 0, 0));
    program.push(Insn::mov64_reg(9, 0));
    // An atomic read of the arming, ordered after the kernel's store to
    // `snd_nxt` -- the other half of the end's exchange.
    program.push(Insn::mov64_imm(1, 0));
    program.push(fetch_add(9, K_ARMED, 1));
    program.jump_to("done", Insn::jne_imm(1, 1, 0));
    read_narrow(&mut program, LIMIT, 4, 6, at.snd_nxt);
    program.push(Insn::ldx(BPF_W, 1, 9, K_TARGET));
    program.push(Insn::stx(BPF_W, R10, SEQ, 1));
    reached(&mut program, LIMIT, SEQ, "reached", "done");
    program.label("reached");
    program.push(Insn::mov64_imm(0, 1));
    program.push(Insn::mov64_imm(1, 0));
    program.push(cmpxchg(9, K_ARMED, 1));
    program.jump_to("done", Insn::jne_imm(0, 1, 0));

    for slot in 0..(RECORD_BYTES / 8) as i16 {
        program.push(Insn::st_imm(BPF_DW, R10, REC + slot * 8, 0));
    }
    program.push(Insn::call(helper::KTIME_GET_NS));
    program.push(Insn::stx(BPF_DW, R10, REC + R_DRAINED, 0));
    program.push(Insn::ldx(BPF_DW, 1, 9, K_ID));
    program.push(Insn::stx(BPF_DW, R10, REC + R_ID, 1));
    program.push(Insn::stx(BPF_DW, R10, REC + R_DECLARED, 1));
    program.push(Insn::ldx(BPF_DW, 1, 9, K_DONE));
    program.push(Insn::stx(BPF_DW, R10, REC + R_DONE, 1));
    program.push(Insn::ldx(BPF_W, 1, 9, K_TID));
    program.push(Insn::stx(BPF_W, R10, REC + R_TID, 1));
    program.push(Insn::ldx(BPF_DW, 1, R10, SOCK_KEY));
    program.push(Insn::stx(BPF_DW, R10, REC + R_COOKIE, 1));
    program.push(Insn::st_imm(BPF_W, R10, REC + R_FLAGS, DRAINED as i32));
    program.push(Insn::st_imm(
        BPF_W,
        R10,
        REC + R_NET_FLAGS,
        NET_DECLARED as i32,
    ));
    program.extend(Insn::load_map_fd(1, maps.ring));
    program.push(Insn::mov64_reg(2, R10));
    program.push(Insn::add64_imm(2, REC as i32));
    program.push(Insn::mov64_imm(3, RECORD_BYTES as i32));
    program.push(Insn::mov64_imm(4, 0));
    program.push(Insn::call(helper::RINGBUF_OUTPUT));
    program.jump_to("done", Insn::jsge_imm(0, 0, 0));
    count_drop(&mut program, maps.counters, DROP_KEY, DROP_RING, "done");
    finish(program)
}

/// Either half of `sk_wait_data(sk, ...)` or `sk_stream_wait_memory(sk, ...)`:
/// marks the serving thread as waiting on its request's socket, or clears the
/// mark. `settle` reads the mark as it was at the switch-out, so a sleep inside
/// the wait is the socket's and every other sleep is not.
///
/// Only the request's own socket counts: a thread that waits on a backend's
/// socket while it serves is waiting for that backend, which is not the
/// client's network.
fn wait_instructions(maps: NetMaps, mark: i32) -> Result<Vec<Insn>, String> {
    let mut program = Program::new();
    program.push(Insn::ldx(BPF_DW, 6, 1, 0));
    program.push(Insn::call(GET_CURRENT_TASK_BTF));
    program.push(Insn::mov64_reg(2, 0));
    program.extend(Insn::load_map_fd(1, maps.storage));
    program.push(Insn::mov64_imm(3, 0));
    program.push(Insn::mov64_imm(4, 0));
    program.push(Insn::call(TASK_STORAGE_GET));
    program.jump_to("done", Insn::jeq_imm(0, 0, 0));
    program.push(Insn::mov64_reg(7, 0));
    if mark == 0 {
        program.push(Insn::st_imm(BPF_W, 7, S_NETWAIT, 0));
        return finish(program);
    }
    program.push(Insn::ldx(BPF_DW, 1, 7, S_COOKIE));
    program.jump_to("done", Insn::jeq_imm(1, 0, 0));
    program.jump_to("done", Insn::jeq_imm(6, 0, 0));
    program.push(Insn::mov64_reg(1, 6));
    program.push(Insn::call(GET_SOCKET_COOKIE));
    program.push(Insn::ldx(BPF_DW, 1, 7, S_COOKIE));
    program.jump_to("done", Insn::jne_reg(0, 1, 0));
    program.push(Insn::st_imm(BPF_W, 7, S_NETWAIT, mark));
    finish(program)
}

const ARRIVAL: (&str, &[&[&str]]) = ("tcp_data_ready", &[&["sock *"]]);
const TRANSMIT: (&str, &[&[&str]]) = ("tcp_event_new_data_sent", &[&["sock *", "sk_buff *"]]);
const RX_WAIT: (&str, &[&[&str]]) = ("sk_wait_data", &[&["sock *", "long int *", "sk_buff *"]]);
const TX_WAIT: (&str, &[&[&str]]) = ("sk_stream_wait_memory", &[&["sock *", "long int *"]]);

/// The kernel functions the network rows are read from, for the catalog's
/// requirements and for the refusal that names them.
pub(super) const FUNCTIONS: [&str; 4] = [ARRIVAL.0, TRANSMIT.0, RX_WAIT.0, TX_WAIT.0];

/// The socket programs, attached, and the map they share with the probes.
pub(super) struct SocketPrograms {
    /// Links first, so they detach before the map they write closes.
    pub links: Vec<Link>,
    pub sockets: OwnedFd,
}

impl SocketPrograms {
    /// Everything or nothing: a request whose arrival is seen and whose drain
    /// is not would have one network row and not the other, and read as a
    /// request that sent nothing.
    pub(super) fn attach(storage: i32, ring: i32, counters: i32) -> Result<Self, String> {
        let btf = super::super::kernel_btf()?;
        let at = Offsets::read(btf)?;
        let sockets = map_create_lru()?;
        let maps = NetMaps {
            storage,
            sockets: sockets.as_raw_fd(),
            ring,
            counters,
        };
        let mut links = Vec::new();
        for ((function, shapes), side, instructions, name) in [
            (
                RX_WAIT,
                Side::Entry,
                wait_instructions(maps, WAIT_RX)?,
                "omn_req_rxw_in",
            ),
            (
                RX_WAIT,
                Side::Exit,
                wait_instructions(maps, 0)?,
                "omn_req_rxw_out",
            ),
            (
                TX_WAIT,
                Side::Entry,
                wait_instructions(maps, WAIT_TX)?,
                "omn_req_txw_in",
            ),
            (
                TX_WAIT,
                Side::Exit,
                wait_instructions(maps, 0)?,
                "omn_req_txw_out",
            ),
            (
                TRANSMIT,
                Side::Exit,
                transmit_instructions(&at, maps)?,
                "omn_req_tx",
            ),
            (
                ARRIVAL,
                Side::Entry,
                arrival_instructions(maps)?,
                "omn_req_rx",
            ),
        ] {
            let target = fentry::expect(function, shapes)?;
            links.push(fentry::attach(&target, side, &instructions, name)?);
        }
        Ok(Self { links, sockets })
    }

    pub(super) fn skipped(&self) -> u64 {
        fentry::misses(&self.links)
    }
}

fn map_create_lru() -> Result<OwnedFd, String> {
    syscall::map_create(
        BPF_MAP_TYPE_LRU_HASH,
        8,
        SOCKET_BYTES as u32,
        MAX_SOCKETS,
        "omn_req_sock",
    )
    .map_err(|error| map_failure("request socket map", error))
}

pub(super) fn offsets() -> Result<Offsets, String> {
    Offsets::read(super::super::kernel_btf()?)
}

#[cfg(test)]
pub(super) mod tests {
    use super::*;

    pub(in crate::bpf) const MAPS: NetMaps = NetMaps {
        storage: 3,
        sockets: 8,
        ring: 6,
        counters: 7,
    };

    fn kernel_btf() -> Option<&'static Btf> {
        match super::super::super::kernel_btf() {
            Ok(btf) => Some(btf),
            Err(reason) => {
                eprintln!("skipped: {reason}");
                None
            }
        }
    }

    /// The fields the walk reads are all in this kernel, and `sock_common` is
    /// where a `sock` begins -- the cookie is read at that sum.
    #[test]
    fn the_walk_from_a_descriptor_to_a_socket_is_this_kernels() {
        let Some(btf) = kernel_btf() else { return };
        Offsets::read(btf).expect("every field the walk reads");
        assert_eq!(btf.member_offset("sock", "__sk_common"), Ok(0));
    }

    /// The four functions have the prototypes the programs read their
    /// arguments out of.
    #[test]
    fn the_socket_functions_have_the_prototypes_the_programs_read() {
        if kernel_btf().is_none() {
            return;
        }
        for (function, shapes) in [ARRIVAL, TRANSMIT, RX_WAIT, TX_WAIT] {
            fentry::expect(function, shapes).expect("a known prototype");
        }
    }

    /// TCP's `after()`, the way `reached` computes it, over the wrap.
    #[test]
    fn a_sequence_number_reaches_its_target_across_the_wrap() {
        let reached =
            |sent: u32, target: u32| ((sent as u64).wrapping_sub(target as u64) << 32) as i64 >= 0;
        assert!(reached(100, 100));
        assert!(reached(101, 100));
        assert!(!reached(99, 100));
        assert!(reached(5, u32::MAX - 5));
        assert!(!reached(u32::MAX - 5, 5));
    }

    /// Exactly one side stamps a drain: the transmit program claims the arming
    /// with a compare-and-exchange from one to zero, and so does the end.
    #[test]
    fn the_drain_is_claimed_by_compare_and_exchange_on_both_sides() {
        let Some(btf) = kernel_btf() else { return };
        let at = Offsets::read(btf).unwrap();
        let claims = |program: &[Insn]| {
            program
                .iter()
                .filter(|insn| insn.code == BPF_STX_ATOMIC_DW && insn.imm == BPF_CMPXCHG)
                .count()
        };
        assert_eq!(claims(&transmit_instructions(&at, MAPS).unwrap()), 1);
        let mut end = Program::new();
        end_socket(&mut end, &at, MAPS.sockets);
        end.push(Insn::mov64_imm(0, 0));
        end.push(Insn::exit());
        assert_eq!(claims(&end.build()), 1);
    }

    /// Only the arrival program inserts into the socket map, and it inserts
    /// only where there is no entry: a second arrival must not move the first
    /// byte's stamp.
    #[test]
    fn only_the_arrival_inserts_and_never_over_an_entry() {
        let Some(btf) = kernel_btf() else { return };
        let at = Offsets::read(btf).unwrap();
        let inserts = |program: &[Insn]| {
            program
                .windows(2)
                .filter(|pair| pair[1].code == 0x85 && pair[1].imm == helper::MAP_UPDATE_ELEM)
                .map(|pair| pair[0].code == 0xb7 && pair[0].imm == BPF_NOEXIST)
                .collect::<Vec<bool>>()
        };
        assert_eq!(inserts(&arrival_instructions(MAPS).unwrap()), vec![true]);
        assert!(inserts(&transmit_instructions(&at, MAPS).unwrap()).is_empty());
        for mark in [WAIT_RX, WAIT_TX, 0] {
            assert!(inserts(&wait_instructions(MAPS, mark).unwrap()).is_empty());
        }
    }
}
